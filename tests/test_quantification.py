# The grain of the confusion matrix -- a bug that was made, caught, and is now pinned
# ---------------------------------------------------------------------------------------

def test_the_confusion_matrix_must_be_estimated_at_the_grain_it_is_applied_to():
    """ACC solves `M p = q`; `q` is specimen-level, so `M` must be too.

    Averaging a shrimp's photographs removes error, so a specimen-level classifier is better than
    the image-level one it is built from. A matrix estimated from images therefore overstates
    confusion, and applying it to specimen-level proportions makes ACC over-correct.

    Constructed here so the failure is unambiguous: each specimen has three photographs, and the
    per-image predictions are wrong often enough that image-level accuracy is poor -- but the
    majority of each specimen's photographs is right, so averaging recovers the truth exactly.
    The image-level matrix says the classifier is bad; the specimen-level matrix says it is
    perfect; and only the second is true of the thing ACC is being handed.
    """
    # Six specimens, three photographs each. Two of every three photographs are correct.
    truth = np.array([0, 0, 1, 1, 2, 3])
    ids, labels, rows = [], [], []
    for k, cls in enumerate(truth):
        wrong = (cls + 1) % 4
        for photo_class in (cls, cls, wrong):
            ids.append(f"s{k}")
            labels.append(cls)
            rows.append(photo_class)
    ids = np.array(ids)
    labels = np.array(labels)
    probs = onehot(np.array(rows))

    image_level = Q.confusion_from_validation(probs, labels)
    specimen_level = Q.confusion_at_specimen_grain(probs, labels, ids)

    assert np.diag(image_level).mean() == pytest.approx(2 / 3), (
        "image-level accuracy is 2 of every 3 photographs, by construction"
    )
    # Averaging 2-of-3 correct photographs recovers every specimen's true class exactly.
    np.testing.assert_allclose(specimen_level, np.eye(4), atol=1e-12)
    assert not np.allclose(image_level, specimen_level), (
        "if these ever agree, this test has stopped testing anything"
    )


def test_using_the_wrong_grain_biases_the_corrected_estimate():
    """The consequence, measured rather than argued.

    Same construction. The specimen-level classifier is perfect, so CC on specimen posteriors is
    already exact and ACC with the right matrix must leave it alone. ACC with the image-level
    matrix "corrects" an error that is not there.
    """
    truth = np.array([0, 1, 1, 3, 3, 3, 2, 2])
    ids, labels, rows = [], [], []
    for k, cls in enumerate(truth):
        wrong = (cls + 1) % 4
        for photo_class in (cls, cls, wrong):
            ids.append(f"s{k}")
            labels.append(cls)
            rows.append(photo_class)
    ids, labels = np.array(ids), np.array(labels)
    probs = onehot(np.array(rows))

    specimen_probs, _ = Q.aggregate_to_specimen(probs, ids)
    true_prevalence = float(np.isin(truth, POSITIVE).mean())

    right = Q.adjusted_count(
        specimen_probs, Q.confusion_at_specimen_grain(probs, labels, ids), POSITIVE)
    wrong = Q.adjusted_count(
        specimen_probs, Q.confusion_from_validation(probs, labels), POSITIVE)

    assert right.prevalence == pytest.approx(true_prevalence, abs=1e-9)
    assert abs(wrong.prevalence - true_prevalence) > abs(right.prevalence - true_prevalence), (
        "the image-level matrix must make the estimate worse, or the grain does not matter"
    )


def test_the_grain_safe_api_refuses_an_inconsistent_specimen():
    with pytest.raises(ValueError, match="class labels"):
        Q.confusion_at_specimen_grain(
            onehot(np.array([0, 1])), np.array([0, 1]), np.array(["s0", "s0"]))
