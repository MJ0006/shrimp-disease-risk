POSITIVE = Q.positive_indices()  # BG_WSSV and WSSV -> indices 1 and 3


def onehot(labels: np.ndarray, n_classes: int = 4) -> np.ndarray:
    """Posteriors from a perfectly confident classifier -- probability 1 on the named class."""
    out = np.zeros((len(labels), n_classes), dtype="float64")
    out[np.arange(len(labels)), labels] = 1.0
    return out


def predictions_matching(counts: np.ndarray) -> np.ndarray:
    """One-hot posteriors whose predicted-class counts are exactly `counts`.

    Lets a test hand an estimator a prediction distribution it chose, so the value that comes back
    can be checked against arithmetic rather than against another run of the same code.
    """
    labels = np.repeat(np.arange(len(counts)), counts.astype("int64"))
    return onehot(labels, len(counts))


