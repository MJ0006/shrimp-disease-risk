"""Tests for the prevalence bridge -- calibration, estimators, and pool construction.

Why these tests are written against analytic answers
----------------------------------------------------
Stage 8's headline claim is that the corrected estimators remove a bias the naive count cannot.
Experiment 07 measures that on real posteriors, where the right answer is only known because the
pools were constructed. If the measurement comes out negative, the first question a panel asks is
whether the estimators were implemented correctly -- and "the experiment says so" is circular.

So the estimators are pinned here against cases where the correct output can be derived on paper:
a confusion matrix inverted exactly, an EM procedure recovering a prior shift generated by
construction, a perfect classifier that must return the truth. This is the same device
`test_deviance_recovers_known_variance_function` provides for Stage 6, and it is what makes a
negative experimental result a statement about the data rather than a suspicion about the code.

None of these need the image corpus, so none are marked `dataset` -- they run everywhere.
"""

from __future__ import annotations

import sys
