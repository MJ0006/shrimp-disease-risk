def test_confusion_columns_are_true_classes_and_sum_to_one():
    """`M[i, j] = P(predict i | true j)`. Transposed, it looks plausible and is wrong."""
    val_labels = np.array([0, 0, 0, 0, 1, 1, 2, 3])
    preds = np.array([0, 0, 0, 1, 1, 1, 2, 3])  # one BG mistaken for BG_WSSV
    M = Q.confusion_from_validation(onehot(preds), val_labels)

    np.testing.assert_allclose(M.sum(axis=0), np.ones(4))
    assert M[0, 0] == pytest.approx(0.75)
    assert M[1, 0] == pytest.approx(0.25), "entry [predicted, true] -- not [true, predicted]"


def test_a_class_absent_from_validation_gets_an_identity_column():
    """A zero column makes the solve singular. The least-assuming stand-in is 'not confused'."""
    val_labels = np.array([0, 0, 1, 1])
    M = Q.confusion_from_validation(onehot(np.array([0, 0, 1, 1])), val_labels)
    assert M[2, 2] == 1.0 and M[3, 3] == 1.0
    np.testing.assert_allclose(M.sum(axis=0), np.ones(4))


def test_soft_confusion_uses_posterior_mass_not_hard_counts():
    val_labels = np.array([0, 0])
    probs = np.array([[0.6, 0.4, 0.0, 0.0],
                      [0.8, 0.2, 0.0, 0.0]])
