def test_specimen_level_weighting_actually_changes_the_answer():
    """The reason aggregation exists, demonstrated rather than asserted.

    One positive shrimp photographed five times and four negative shrimp photographed once each:
    image-level counting reports 5/9 positive, specimen-level reports 1/5. If these two ever agree
    the aggregation has stopped doing anything.
    """
    labels = np.array([3] * 5 + [2] * 4)
    ids = np.array(["WSSV-1"] * 5 + [f"Healthy-{i}" for i in range(4)])
    probs = onehot(labels)

    image_level = Q.classify_and_count(probs, POSITIVE).prevalence
    specimen_probs, _ = Q.aggregate_to_specimen(probs, ids)
    specimen_level = Q.classify_and_count(specimen_probs, POSITIVE).prevalence

    assert image_level == pytest.approx(5 / 9)
    assert specimen_level == pytest.approx(1 / 5)


