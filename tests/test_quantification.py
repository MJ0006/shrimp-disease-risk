def test_temperature_one_leaves_the_posteriors_alone():
    probs = np.array([[0.7, 0.2, 0.05, 0.05], [0.1, 0.1, 0.6, 0.2]])
    np.testing.assert_allclose(apply_temperature(probs, 1.0), probs, atol=1e-12)


def test_probs_to_logits_round_trips_through_the_softmax():
    """The identity the module rests on: log(p) recovers the logits up to a shift that cancels."""
    probs = np.array([[0.7, 0.2, 0.05, 0.05], [0.1, 0.1, 0.6, 0.2]])
    logits = probs_to_logits(probs)
    exp = np.exp(logits - logits.max(axis=1, keepdims=True))
    np.testing.assert_allclose(exp / exp.sum(axis=1, keepdims=True), probs, atol=1e-12)


def test_temperature_scaling_cannot_change_the_prediction():
    """Why calibration is safe to apply after Stage 5: accuracy and macro-F1 cannot move."""
    rng = np.random.default_rng(3)
    logits = rng.normal(size=(500, 4))
    exp = np.exp(logits - logits.max(axis=1, keepdims=True))
    probs = exp / exp.sum(axis=1, keepdims=True)

    for T in (0.25, 0.5, 2.0, 5.0):
        assert (apply_temperature(probs, T).argmax(1) == probs.argmax(1)).all()


def test_fitting_an_overconfident_model_returns_a_temperature_above_one():
    """The direction that matters. `D-028` found these models overconfident by +0.197."""
    rng = np.random.default_rng(11)
    n = 4000
    labels = rng.integers(0, 4, size=n)
    logits = np.zeros((n, 4))
    logits[np.arange(n), labels] = 4.0                     # very peaked
    wrong = rng.random(n) < 0.35                           # but wrong 35% of the time
    logits[wrong] = np.roll(logits[wrong], 1, axis=1)
    exp = np.exp(logits - logits.max(axis=1, keepdims=True))
    probs = exp / exp.sum(axis=1, keepdims=True)

    before = expected_calibration_error(probs, labels)
    T, info = fit_temperature(probs, labels)
    after = expected_calibration_error(apply_temperature(probs, T), labels)

    assert T > 1.0, "an overconfident model must be softened, not sharpened"
    assert not info["at_bound"]
    assert after["ece"] < before["ece"]
    assert info["nll_after"] <= info["nll_before"]


def test_the_fitted_temperature_is_deterministic():
    """No learning rate, no seed: two runs of the fit cannot disagree."""
    rng = np.random.default_rng(5)
    probs = rng.dirichlet(np.ones(4), size=800)
    labels = rng.integers(0, 4, size=800)
    assert fit_temperature(probs, labels)[0] == fit_temperature(probs, labels)[0]


def test_nll_is_minimised_by_the_truth():
    """The reason NLL is the objective and ECE only the report: NLL is strictly proper."""
    labels = np.array([0, 1, 2, 3])
    truth = onehot(labels) * 0.97 + 0.01
    wrong = np.roll(truth, 1, axis=1)
    assert negative_log_likelihood(truth, labels) < negative_log_likelihood(wrong, labels)


