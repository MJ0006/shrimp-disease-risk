"""Build and execute `shrimp_disease_risk_project.ipynb` -- the project as a readable notebook.

Why a notebook, when the project is a package plus scripts
----------------------------------------------------------
A guide reads a notebook. Code, output and explanation sit together in one file that opens in a
browser and can be scrolled through without a terminal, which is how project work is normally
reviewed at this level. The package and the experiment scripts remain the source of truth --
**this notebook imports them rather than restating them**, so there is exactly one implementation
of every claim in the project and no second copy to drift.

Why the notebook is generated by a script
-----------------------------------------
Same reason the figures are (`D-014`): an artefact nobody can regenerate cannot be defended. Rerun
this after any experiment and the notebook is rebuilt from the current tables, run artefacts and
module source, then executed so every output in it is real. A notebook edited by hand would
silently go stale the moment a table changed.

**Anything edited directly in the .ipynb is lost on the next build.** Edit the cells here.

What is live and what is replayed
---------------------------------
The notebook trains a model **for real**, once: one specimen-level fold of
`mobilenetv3_large_100` for a few epochs, about a minute on the project's GPU. That is a
*demonstration* run and is labelled as one wherever it appears -- it is not written to
`experiments/runs/` and no reported number comes from it.

Everything else is either recomputed in seconds from raw inputs (the manifest, the stored
posteriors, the Just-Pope mean equation) or read from the run artefact that produced it, with
the file named. The reported results took ~75 minutes of GPU time and cannot be reproduced in a
notebook read-through; pretending otherwise would be the one failure that discredits the rest
(`D-022`).

Usage
-----
    .venv/Scripts/python.exe scripts/build_notebook.py                # build + execute (~5 min)
    .venv/Scripts/python.exe scripts/build_notebook.py --no-execute   # source cells only
    .venv/Scripts/python.exe scripts/build_notebook.py --epochs 3     # shorter demo training
"""

