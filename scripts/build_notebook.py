def build(epochs: int, execute: bool) -> int:
    notebook = new_notebook(cells=cells(epochs))
    notebook.metadata.update({
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python"},
    })
    nbformat.write(notebook, NOTEBOOK)
    print(f"wrote {len(notebook.cells)} cells -> {NOTEBOOK.relative_to(PROJECT_ROOT)}")

    if not execute:
        print("not executed (--no-execute); the notebook has no outputs")
        return 0

    from nbclient import NotebookClient

    print("executing ... (a real training run happens in section 5)")
    started = time.time()
    client = NotebookClient(
        notebook,
        timeout=1800,
        kernel_name="python3",
        resources={"metadata": {"path": str(PROJECT_ROOT)}},
    )
    client.execute()
    nbformat.write(notebook, NOTEBOOK)

    executed = sum(1 for cell in notebook.cells if cell.cell_type == "code")
    errors = [cell for cell in notebook.cells
              if any(output.get("output_type") == "error" for output in cell.get("outputs", []))]
    print(f"executed {executed} code cells in {time.time() - started:.0f} s, "
          f"{len(errors)} with errors")
    return 1 if errors else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--no-execute", action="store_true",
                        help="write the source cells without running them")
    parser.add_argument("--epochs", type=int, default=8,
                        help="epoch budget for the live demonstration run (default 8)")
    args = parser.parse_args(argv)
    return build(epochs=args.epochs, execute=not args.no_execute)


